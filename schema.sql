CREATE DATABASE IF NOT EXISTS student_performance;
USE student_performance;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('student','teacher') NOT NULL DEFAULT 'student',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS performance (
 id INT AUTO_INCREMENT PRIMARY KEY,
 student_id INT NOT NULL UNIQUE,
 math_marks DECIMAL(5,2) NOT NULL DEFAULT 0,
 science_marks DECIMAL(5,2) NOT NULL DEFAULT 0,
 english_marks DECIMAL(5,2) NOT NULL DEFAULT 0,
 attendance DECIMAL(5,2) NOT NULL DEFAULT 0,
 study_hours DECIMAL(5,2) NOT NULL DEFAULT 2,
 previous_score DECIMAL(5,2) NOT NULL DEFAULT 50,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE
);
